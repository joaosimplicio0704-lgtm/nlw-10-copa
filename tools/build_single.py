#!/usr/bin/env python3
"""
build_single.py — collapse fortnite_external.cpp + offsets_gen.hpp into one file.

    python3 tools/build_single.py

Writes fortnite-external/fortnite_external_single.cpp: same program with no local
includes, so it is a single translation unit you can drop into an MSVC project or
a command line. Nothing is elided, nothing is #ifdef'd out — there is no driver
half any more.

Then it runs the compile gate (tools/syntax_check.py) against the result.
"""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "fortnite-external", "fortnite_external.cpp")
OFF = os.path.join(ROOT, "fortnite-external", "offsets_gen.hpp")
OUT = os.path.join(ROOT, "fortnite-external", "fortnite_external_single.cpp")
DUMP = os.path.join(ROOT, "tools", "fortnite_offsets_43.00.json")

BANNER = """\
// ============================================================================
//  fortnite_external_single.cpp — ONE FILE, no local includes.
//
//  GENERATED by tools/build_single.py from:
//    fortnite-external/fortnite_external.cpp
//    fortnite-external/offsets_gen.hpp   (tools/gen_offsets.py + the v43.00 dump)
//
//  Edit those two, then regenerate:
//    python3 tools/build_single.py
//
//  User-mode external only: OpenProcess(PROCESS_VM_READ |
//  PROCESS_QUERY_INFORMATION) + ReadProcessMemory + SendInput + D3D9Ex overlay.
//  No driver, no physical memory, no writes to the game, no injection.
//
//  Build (MSVC x64 Developer prompt, this folder):
//    cl /nologo /std:c++17 /O2 /EHsc /W3 /D_CRT_SECURE_NO_WARNINGS ^
//       fortnite_external_single.cpp ^
//       /link /SUBSYSTEM:CONSOLE /OUT:fortnite_external.exe ^
//       d3d9.lib dwmapi.lib user32.lib gdi32.lib psapi.lib winmm.lib
//
//  or just run build.bat, which finds vcvars64 for you.
//
//  Keys: INSERT menu · END unload · aim key HELD to aim (RMB by default).
//  Aimbot and visuals start disabled.
// ============================================================================

"""


def strip_pragma_once(text):
    import re
    return re.sub(r"^#pragma once\s*$\n", "", text, flags=re.MULTILINE)


def main():
    with open(SRC, "r", encoding="utf-8") as fh:
        src = fh.read()
    with open(OFF, "r", encoding="utf-8") as fh:
        off = fh.read()

    if '#include "offsets_gen.hpp"' not in src:
        print("error: offsets_gen.hpp include not found in the source", file=sys.stderr)
        return 1

    # keep the header's own provenance comment, drop the pragma (single TU)
    off = strip_pragma_once(off)

    inline_off = (
        "// ---------------------------------------------------------------------------\n"
        "//  offsets_gen.hpp  (inlined, generated — do not hand-edit)\n"
        "// ---------------------------------------------------------------------------\n"
        + off
        + "\n// --------------------------- end offsets_gen.hpp ---------------------------\n"
    )
    out = src.replace('#include "offsets_gen.hpp"', inline_off, 1)

    if '#include "offsets_gen.hpp"' in out:
        print("error: more than one offsets_gen.hpp include", file=sys.stderr)
        return 1
    if "_KERNEL_MODE" in out:
        print("error: kernel-mode half reappeared", file=sys.stderr)
        return 1

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(out)

    print(f"wrote {os.path.relpath(OUT, ROOT)}  ({out.count(chr(10))} lines, "
          f"{os.path.getsize(OUT)} bytes)")

    gate = os.path.join(ROOT, "tools", "syntax_check.py")
    if not os.path.exists(gate):
        print("no compile gate present", file=sys.stderr)
        return 1

    result = subprocess.run([sys.executable, gate, OUT], capture_output=True, text=True)
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        print("compile gate FAILED", file=sys.stderr)
        return 1
    print("compile gate OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
