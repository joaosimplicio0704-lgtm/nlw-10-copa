#!/usr/bin/env python3
"""
build_single.py — collapse fortnite_external.cpp + offsets_gen.hpp into one file.

    python3 tools/build_single.py

Writes fortnite-external/fortnite_external_single.cpp: same program, no includes
of local headers, so it is a single translation unit you can drop into an MSVC
project or a WDK driver project as-is.

After building, the single file is syntax-checked with tools/syntax_check.py.
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "fortnite-external", "fortnite_external.cpp")
OFF = os.path.join(ROOT, "fortnite-external", "offsets_gen.hpp")
OUT = os.path.join(ROOT, "fortnite-external", "fortnite_external_single.cpp")

BANNER = """\
// ============================================================================
//  fortnite_external_single.cpp — ONE FILE, no local includes.
//
//  Generated by tools/build_single.py from:
//    fortnite-external/fortnite_external.cpp
//    fortnite-external/offsets_gen.hpp      (from tools/gen_offsets.py + the
//                                            v43.00 OffsetDeck dump)
//
//  Build (MSVC x64 Developer prompt, this folder):
//    cl /std:c++17 /O2 /EHsc /W3 /D_CRT_SECURE_NO_WARNINGS ^
//       fortnite_external_single.cpp /link /SUBSYSTEM:CONSOLE /OUT:fortnite_external.exe
//
//  Driver (WDK "Empty WDM Driver", x64/Release): same file, add _KERNEL_MODE to
//  Preprocessor Definitions, build. Only the _KERNEL_MODE half is compiled then.
//
//  Regenerate after touching either input:
//    python3 tools/build_single.py
// ============================================================================

"""


def strip_pragma_once(text):
    return re.sub(r"^#pragma once\s*$\n", "", text, flags=re.MULTILINE)


def main():
    with open(SRC, "r", encoding="utf-8") as fh:
        src = fh.read()
    with open(OFF, "r", encoding="utf-8") as fh:
        off = fh.read()

    off = strip_pragma_once(off)

    if '#include "offsets_gen.hpp"' not in src:
        print("error: offsets_gen.hpp include not found in the source", file=sys.stderr)
        return 1

    # swap the local header include for the header's own body, indented comment rule
    inline_off = (
        "// ---------------------------------------------------------------------------\n"
        "//  offsets_gen.hpp  (inlined, generated — do not hand-edit)\n"
        "// ---------------------------------------------------------------------------\n"
        + off
        + "\n// --------------------------- end offsets_gen.hpp ---------------------------\n"
    )
    out = src.replace('#include "offsets_gen.hpp"', inline_off, 1)

    # single-use guard against a stale include of the generated header
    if '#include "offsets_gen.hpp"' in out:
        print("error: more than one offsets_gen.hpp include", file=sys.stderr)
        return 1

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(out)

    lines = out.count("\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}  ({lines} lines, {os.path.getsize(OUT)} bytes)")

    # syntax gate against the single file
    check = os.path.join(ROOT, "tools", "syntax_check.py")
    result = subprocess.run([sys.executable, check, OUT], capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        print("syntax check FAILED", file=sys.stderr)
        return 1
    print("syntax check OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
